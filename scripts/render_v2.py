def section_options(rqs):
    sections = [(f"sec-{i:02d}", n) for i, n in enumerate([
        "Resumo", "Introdução", "Background", "Metodologia",
        "Resultados", "Síntese", "Discussão", "Limitações",
        "Conclusão", "NÃO é", "Referências",
    ])]
    return "\n".join(
        f'<option value="{html_escape(sid)}">{html_escape(name)}</option>'
        for sid, name in sections
    )


def rq_options(rqs):
    return "\n".join(
        f'<option value="rq-{i+1}">RQ{i+1}</option>'
        for i in range(len(rqs))
    )


def replace_inline_ref_markers(html_text: str, refs: list[dict]) -> str:
    """Faz [n] → <a href="#ref-n">[n]</a>"""
    def replace(match):
        n = match.group(1)
        return f'<a href="#ref-{n}" class="cite">[{n}]</a>'
    return re.sub(r'\[(\d+)\]', replace, html_text or "")


