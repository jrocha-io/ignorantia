def html_escape(s: str) -> str:
    return html.escape(s or "", quote=True)


def _maybe_prepend_contextual_preamble(introduction_html: str, args, content: dict,
                                         topic_kws: list) -> str:
    """F4 (v2.18.1, DD-11): se --contextual-preamble flag estiver ativa, gera
    seção 'O campo onde este artigo vive' (Wikipedia + Wikidata) e prepend ao HTML
    da Introdução. Seção é distinta da Introdução: apresenta o campo, não a pesquisa.

    Falha graciosamente se contextual_preamble.py não está disponível ou se
    fetch da Wikipedia falha — neste caso, render normal (sem preâmbulo).
    """
    if not getattr(args, "contextual_preamble", False):
        return introduction_html

    try:
        from contextual_preamble import ContextualPreamble, _mock_preamble
    except ImportError:
        # Não bloqueia render se módulo ausente
        return introduction_html

    topic = args.preamble_topic or args.topic_slug.replace("-", " ")
    area = args.preamble_area or (args.area_mae or "multi")
    # Normalizar área para chave esperada
    area_normalized = area.lower().strip()
    if area_normalized not in ContextualPreamble.AREA_TO_DISCIPLINE_MAP:
        area_normalized = "multi"
    language = args.preamble_language or "pt-BR"

    if args.preamble_mock:
        cp = _mock_preamble(topic, area_normalized, language)
    else:
        cp = ContextualPreamble(language=language)
        cp.set_topic(topic, area=area_normalized)
        try:
            cp.fetch_wikipedia_context()
            cp.fetch_wikidata_entities()
        except Exception:
            # Erros emitem warnings via WikimediaFetchWarning;
            # se tudo falhou, render_html já mostra contextual-warning.
            pass

    preamble_html = cp.render_html()
    return preamble_html + "\n" + introduction_html



def file_text(path: str | Path) -> str:
    p = Path(path)
    if not p.exists():
        return ""
    return p.read_text(encoding="utf-8", errors="ignore")


def load_json(path: str | Path) -> Any:
    p = Path(path)
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def load_csv(path: str | Path) -> list[dict]:
    p = Path(path)
    if not p.exists():
        return []
    with open(p, "r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


