# ── Notes (críticas, importantes, polimento) ────────────────────────────


def build_notes_html(notes: dict, lang: str = "pt-BR") -> str:
    """Renderiza listagem do que falta para nota máxima."""
    is_ptbr = lang.lower().startswith("pt")
    sections = []
    for severity, label, color in [
        ("critical", "Crítico" if is_ptbr else "Critical", "var(--bad)"),
        ("important", "Importante" if is_ptbr else "Important", "var(--med)"),
        ("polish", "Polimento" if is_ptbr else "Polish", "var(--lo)"),
    ]:
        items = notes.get(severity, [])
        if not items:
            continue
        items_html = "\n".join(f'<li>{html_escape(item)}</li>' for item in items)
        sections.append(
            f'<div style="margin:16px 0">'
            f'<h4 style="color:{color};margin:0 0 8px">{label} ({len(items)})</h4>'
            f'<ul style="margin:0;font-size:13px">{items_html}</ul>'
            f'</div>'
        )
    if not sections:
        msg = "Nenhuma observação. Trabalho atende todos os critérios." if is_ptbr \
              else "No observations. Work meets all criteria."
        return f'<p style="color:var(--good)">✅ {msg}</p>'
    return "\n".join(sections)


# ── Plagiarism ──────────────────────────────────────────────────────────


def build_plagiarism_html(plagiarism: dict, lang: str = "pt-BR") -> str:
    """Renderiza relatório de plágio camada 1."""
    is_ptbr = lang.lower().startswith("pt")
    n_critical = plagiarism.get("critical_matches", 0)
    n_warning = plagiarism.get("warning_matches", 0)
    n_legitimate = plagiarism.get("legitimate_matches", 0)
    n_phrases = plagiarism.get("n_phrases_checked", 0)
    n_sources = plagiarism.get("n_sources_compared", 0)

    if n_critical == 0 and n_warning == 0:
        msg = "Nenhum match crítico ou warning detectado na camada 1." if is_ptbr \
              else "No critical or warning matches detected in layer 1."
        out = f'<p style="color:var(--good)">✅ {msg}</p>'
    else:
        out = (
            f'<p>'
            f'🔴 <strong>{n_critical}</strong> críticos · '
            f'🟡 <strong>{n_warning}</strong> avisos · '
            f'🟢 <strong>{n_legitimate}</strong> legítimos'
            f'</p>'
        )
    out += (
        f'<p style="font-size:12px;color:var(--text-muted)">'
        f'Camada 1 verificou {n_phrases} frases contra {n_sources} fontes do corpus interno. '
        f'{html_escape(plagiarism.get("advisory", ""))}'
        f'</p>'
    )
    return out


def build_sprint_badge_html(badge: dict, lang: str = "pt-BR",
                              minimal_info: dict | None = None,
                              area_mae: str | None = None) -> str:
    """Renderiza Sprint Badge com disclosure pattern acessível.

    Substitui o tooltip CSS-only (que exigia hover/focus) por um botão
    "ver detalhes" que controla um painel expansível via aria-expanded.
    Acessível em mobile e por leitores de tela.

    Args:
        badge: dict serializado por sprint_badge.serialize_badge
        lang: 'pt-BR' ou 'en'
        minimal_info: dict 'minimal_package_detected' do assessment (opcional)
        area_mae: área-mãe do tema (ex.: 'educacao', 'saude') — usado para
            adicionar aviso de heterogeneidade Qualis quando aplicável.
    """
    if not badge:
        return ""
    is_ptbr = lang.lower().startswith("pt")
    color = badge.get("color", "#9090a8")
    label_pt = badge.get("label_pt", "")
    label_en = badge.get("label_en", "")
    full_tooltip = badge.get("tooltip_pt" if is_ptbr else "tooltip_en", "")
    calibration_version = badge.get("calibration_version", "?")

    # Resumo curto: primeira frase do tooltip ou primeiros 80 chars
