def build_temporal_data(extraction_rows):
    counts = {}
    for r in extraction_rows:
        try:
            y = int(str(r.get("year", "")).strip())
        except ValueError:
            continue
        counts[y] = counts.get(y, 0) + 1
    return sorted([{"year": y, "n": n} for y, n in counts.items()],
                  key=lambda d: d["year"])


def build_qa_heatmap_data(qa_rows):
    """Build {studies: [{id, scores}], dimensions: ['QA1', 'QA2', ...]}.
    Detects QA1..QAN columns (consensus preferred, fallback to reviewer1)."""
    if not qa_rows:
        return {"studies": [], "dimensions": []}
    cols = qa_rows[0].keys()
    consensus_cols = sorted([c for c in cols if c.startswith("consensus_QA")])
    if consensus_cols:
        prefix = "consensus_"
        qcols = consensus_cols
    else:
        qcols = sorted([c for c in cols if c.startswith("reviewer1_QA")])
        prefix = "reviewer1_"
    dims = [c.replace(prefix, "") for c in qcols]
    studies = []
    for r in qa_rows:
        sid = r.get("study_id", "")
        if not sid:
            continue
        scores = []
        for c in qcols:
            try:
                scores.append(float(r.get(c, 0) or 0))
            except ValueError:
                scores.append(0)
        # normalize 0..1 (assuming max is 1 or 2 per question — DARE uses 0/0.5/1)
        mx = max(scores) if scores else 1
        if mx > 1:
            scores = [s / mx for s in scores]
        studies.append({"id": sid, "scores": scores})
    return {"studies": studies, "dimensions": dims}


