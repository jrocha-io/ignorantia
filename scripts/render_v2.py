    # Lista de ajustes
    adjs = badge.get("adjustments_applied", [])
    adj_html = ""
    if adjs:
        adj_label = "Ajustes aplicados:" if is_ptbr else "Adjustments applied:"
        items = "".join(f"<li>{html_escape(a)}</li>" for a in adjs)
        adj_html = (f'<div class="sprint-badge-adjustments">'
                    f'<strong>{adj_label}</strong><ul>{items}</ul></div>')

    # Indicador de modo pacote mínimo (Rodada O)
