# ── Score decomposition ─────────────────────────────────────────────────


def build_dimensions_html(dimensions: list[dict]) -> str:
    """Renderiza decomposição de C1-C7 ou F1-F4 como rows."""
    if not dimensions:
        return '<p style="color:var(--text-muted)">Decomposição não disponível.</p>'
    rows = []
    for d in dimensions:
        pct = (d["points_obtained"] / d["weight"] * 100) if d["weight"] else 0
        rows.append(
            f'<div class="score-decomp-row">'
            f'<span class="score-decomp-name"><strong>{html_escape(d["code"])}</strong> {html_escape(d["name"])}</span>'
            f'<div class="score-decomp-bar"><div class="score-decomp-bar-fill" style="width:{pct:.0f}%"></div></div>'
            f'<span class="score-decomp-points">{d["points_obtained"]:.2f}/{d["weight"]}</span>'
            f'</div>'
        )
    return "\n".join(rows)


