def html_escape(s):
    if s is None:
        return ""
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def qa_badge_class(score):
    """Map a QA total score to a badge class. Score range varies by instrument
    (5 for DARE/Kitchenham, 10 for hybrid). Normalize as fraction."""
    try:
        s = float(score)
    except (TypeError, ValueError):
        return "badge"
    # try to detect scale
    if s > 5:
        frac = s / 10.0
    else:
        frac = s / 5.0
    if frac >= 0.85:
        return "badge badge-qa-hi"
    if frac >= 0.70:
        return "badge badge-qa-mid"
    if frac >= 0.50:
        return "badge badge-qa-lo"
    return "badge badge-qa-bad"


def build_studies_table(extraction_rows, qa_rows):
    """Combine extraction + QA into table rows."""
    qa_by_id = {r.get("study_id"): r for r in qa_rows}
    out = []
    for r in extraction_rows:
        sid = r.get("study_id", "")
        cite = r.get("citation", "")
        year = r.get("year", "")
        venue = r.get("venue", "")
        frameworks = r.get("frameworks", "") or r.get("theoretical_framework", "")
        methods = r.get("methods", "") or r.get("study_type", "")
        rqs = r.get("rq_addressed", "")
        qa = qa_by_id.get(sid, {})
        qa_total = qa.get("consensus_total") or qa.get("reviewer1_total") or r.get("qa_score", "")
        doi = r.get("doi", "")
        # build anchor for citation
        if doi:
            href = f"https://doi.org/{doi.lstrip('https://doi.org/').lstrip('http://doi.org/')}"
            cite_html = f'<a href="{html_escape(href)}" rel="external">{html_escape(cite)}</a>'
        elif r.get("url"):
            cite_html = f'<a href="{html_escape(r["url"])}" rel="external">{html_escape(cite)}</a>'
        else:
            cite_html = html_escape(cite)
        rqs_html = " ".join(
            f'<span class="badge badge-rq">{html_escape(rq.strip())}</span>'
            for rq in re.split(r"[,;]\s*", rqs) if rq.strip()
        )
        qa_html = (f'<span class="{qa_badge_class(qa_total)}">{html_escape(qa_total)}</span>'
                   if qa_total != "" else "")
        rqs_data = ",".join(re.split(r"[,;]\s*", rqs)).lower()
        out.append(
            f'<tr data-id="{html_escape(sid)}" data-rqs="{html_escape(rqs_data)}" '
            f'data-qa="{html_escape(qa_total)}">'
            f'<td>{html_escape(sid)}</td>'
            f'<td>{cite_html}</td>'
            f'<td>{html_escape(year)}</td>'
            f'<td>{html_escape(venue)}</td>'
            f'<td>{html_escape(frameworks)}</td>'
            f'<td>{html_escape(methods)}</td>'
            f'<td>{rqs_html}</td>'
            f'<td>{qa_html}</td>'
            f'</tr>'
        )
    return "\n".join(out)


def build_references_list(refs):
    """Build the <ol> entries with clickable DOIs and anchors."""
    out = []
    for r in refs:
        n = r["n"]
        body = r["html"]  # already-formatted citation per the chosen style
        url = r.get("url") or (f"https://doi.org/{r['doi']}" if r.get("doi") else "")
        link_html = (f' <a class="ref-link doi" href="{html_escape(url)}" rel="external">↗</a>'
                     if url else "")
        out.append(f'<li id="ref-{n}">{body}{link_html}</li>')
    return "\n".join(out)


def build_ref_index_for_text(refs):
    """Return a dict {n: tooltip-text} for use in inline [n] references."""
    return {r["n"]: re.sub(r"<[^>]+>", "", r["html"]) for r in refs}


def replace_inline_ref_markers(html, refs):
    """Replace [n] markers in HTML with anchor tags + tooltips.

    Pattern: [12] or [3,4] or [3-5]. We expand sets and ranges.
    """
    by_n = {r["n"]: r for r in refs}

    def mk_link(n):
        r = by_n.get(int(n))
        if not r:
            return f"[{n}]"
        href = (r.get("url") or
                (f"https://doi.org/{r['doi']}" if r.get("doi") else f"#ref-{n}"))
        tooltip = re.sub(r"<[^>]+>", "", r["html"])
        # escape only attribute-unsafe chars
        tooltip_attr = (tooltip.replace("&", "&amp;").replace('"', "&quot;")
                        .replace("<", "&lt;").replace(">", "&gt;"))
        return (f'<a class="ref" href="{html_escape(href)}" '
                f'data-ref="{n}"><span class="tooltip">[{n}] {tooltip_attr}</span>{n}</a>')

    def expand_match(m):
        inner = m.group(1)
        parts = []
        for chunk in inner.split(","):
            chunk = chunk.strip()
            if "-" in chunk or "–" in chunk:
                a, b = re.split(r"[-–]", chunk, maxsplit=1)
                try:
                    for k in range(int(a), int(b) + 1):
                        parts.append(mk_link(k))
                except ValueError:
                    return m.group(0)
            else:
                try:
                    parts.append(mk_link(int(chunk)))
                except ValueError:
                    return m.group(0)
        return "[" + ",".join(parts) + "]"

    return re.sub(r"\[(\d+(?:\s*[,–-]\s*\d+)*)\]", expand_match, html)


